    /**
     * @see com.ospreydcs.dp.jal.tools.common.datagen.IFrameTimestampsFactory#nextUniformClock(java.time.Instant)
     */
    @Override
    public UniformSamplingClock nextUniformClock() throws IllegalArgumentException {
        
        UniformSamplingClock clk = UniformSamplingClock.from(this.insTmsCurr, this.cntSmpls, this.durPeriod);
        
        this.insTmsCurr = this.advanceFrameStart(this.insTmsCurr);
        
        return clk;
    }

    /**
     * @see com.ospreydcs.dp.jal.tools.common.datagen.IFrameTimestampsFactory#nextTimestampVector(java.time.Instant)
     */
    @Override
    public ArrayList<Instant> nextTimestampVector() throws DateTimeException, ArithmeticException {
        
        ArrayList<Instant>   vecTms = new ArrayList<>(this.cntSmpls);
        
        for (int iTms=0; iTms<this.cntSmpls; iTms++) {
            vecTms.add(insTmsCurr);
            
            insTmsCurr = insTmsCurr.plus(this.durPeriod);     // throws DateTimeException, ArithmeticException
        }
        
        return vecTms;
    }

    
