/**
 * <p>
 * Factory class for simulated timestamp generation used in ingestion frame factories.
 * </p>
 * <p>
 * The timestamps generated by this class are always uniform.  That is, whether a sampling clock
 * or an explicit timestamp list is generated, all timestamps are equally spaced.  The timestamp
 * spacing is determined by the sampled period provided at construction.
 * </p>
 * <p>
 * <h2>Timestamp Types</h2>
 * There are 2 ingestion frame timestamp "types" supported by the Data Platform.  These types are 
 * enumerated in the enumeration <code>{@link DpTimestampCase}</code>:
 * <ol>
 * <li><code>{@link DpTimestampCase#SAMPLING_CLOCK}</code> - timestamps are generated by a uniform sampling clock,</li>
 * <li><code>{@link DpTimestampCase#TIMESTAMP_LIST}</code> - timestamps are contained in an explicit (ordered) list.</li>
 * </ol>
 * The actual ingestion frame timestamps are generated by choice of methods <code>{@link #nextUniformClock(Instant)}</code>
 * and <code>{@link #nextTimestampVector(Instant)}</code>.  The number of timestamps produced by the latter method
 * is determined by the sample count.
 * Note that explict timestamp lists are more expensive than uniform sampling clocks as they require more resources and
 * processing time.
 * </p>
 * <p>
 * <h2>Sample Period</h2>
 * Although explicit timestamp lists are supported by the Data Platform and can have arbitrary spacing within an
 * ingestion frame, this frame timestamp factory always produces uniformly generated timestamps.  The spacing
 * (i.e., time interval) between timestamps is given by the sampling period provided at construction/creation.
 * Note that the sampling frequency is the inverse of the sampling period.
 * <p>
 * <h2>Sample Count</h2>
 * The number timestamps for each ingestion frame is determined by the sample count provided at construction/creation.
 * The sample count is immutable and all invocations of <code>{@link #nextUniformClock(Instant)}</code> and
 * <code>{@link #nextTimestampVector(Instant)}</code> always produce the same number of timestamps.
 * The value returned by <code>{@link #nextFrameStart(Instant)}</code> is determined by the sample count and the 
 * sample period.
 * </p>
 *
 * @author Christopher K. Allen
 * @since Dec 30, 2025
 *
 */
