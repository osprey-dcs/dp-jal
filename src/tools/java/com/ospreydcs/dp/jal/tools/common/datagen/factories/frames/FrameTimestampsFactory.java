    /**
     * <p>
     * Advances the current frame starting time instant according to the period and the sampling count.
     * </p>
     * <p>
     * The returned value is the start time for the next sequence of timestamps generated by either
     * <code>{@link #nextUniformClock()}</code> or <code>{@link #nextTimestampVector()}</code>.  Specifically,
     * if <i>t<sub>n</sub></i> is the start time instant for ingestion frame <i>n</i> then the method
     * returns <i>t</i><sub><i>n</i>+1</sub> given by
     * <pre>
     *   <i>t</i><sub><i>n</i>+1</sub> = <i>t<sub>n</sub></i> + <i>NT</i>
     * </pre>
     * where
     * <ul>
     * <li><i>N</i> = sample count,</li>
     * <li><i>T</i> = sample period.</li>
     * </ul>
     * </p> 
     * 
     * @param insTmsCurr    the current frame start time instant <i>t<sub>n</sub></i>
     *  
     * @return  the next frame start time instant <i>t</i><sub><i>n</i>+1</sub>
     * 
     * @throws DateTimeException    internal <code>Instant</code> addition failed
     * @throws ArithmeticException  numeric overflow occurred in <code>Instant</code> addition 
     */
    private Instant advanceFrameStart(Instant insTmsCurr) throws ArithmeticException, DateTimeException {
        
        Duration    durRange = this.durPeriod.multipliedBy(this.cntSmpls);    // throws ArithmeticException
        Instant     insTmsNext = insTmsCurr.plus(durRange);      // throws DateTimeException, ArithmeticException
        
        return insTmsNext;
    }
